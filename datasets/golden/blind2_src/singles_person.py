def birth_date(g: Gen) -> list[dict]:
    c = "BIRTH_DATE"
    out = []
    styles = (
        ("label_dot", "Дата рождения: ", "dot", ""),
        ("abbr_slash", "д.р. ", "slash", ""),
        ("words_goda", "родился ", "words", " года"),
        ("iso", "ДР ", "iso", ""),
        ("short_year", "родилась ", "short", ", замужем"),
        ("english", "Date of birth: ", "dot", ""),
        ("dash", "рожд. ", "dash", ""),
        ("upper", "ДАТА РОЖДЕНИЯ ", "dot", ""),
        ("words_g", "появился на свет ", "words", " г."),
        ("sentence", "день рождения клиента - ", "dot", ", поздравьте его"),
        ("birth_en", "birth: ", "iso", ""),
        ("gr_suffix", "", "dot", " г.р."),
    )
    for variant, pre, style, post in styles:
        d, m, y = g.date()
        out.append(make(c, variant, pre, P(fmt_date(d, m, y, style), c), post))
    out.append(make(c, "spaces_typo", "дата рожд. ", P("24. 05. 1981", c)))
    out.append(make(c, "nbsp", f"Дата{NBSP}рождения:{NBSP}", P(f"7{NBSP}ноября{NBSP}1969", c), f"{NBSP}г."))
    return out


