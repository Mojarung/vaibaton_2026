_TR = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z",
    "и": "i", "й": "i", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh",
    "щ": "shch", "ъ": "ie", "ы": "y", "ь": "", "э": "e", "ю": "iu", "я": "ia", "-": "-",
}


def translit(word: str) -> str:
    return "".join(_TR.get(ch, ch) for ch in word.lower())


def full(person, order: str = "fio") -> str:
    """ФИО в нужном порядке; пустое отчество пропускается."""
    sur, name, patr, _ = person
    parts = {"fio": (sur, name, patr), "iof": (name, patr, sur), "fi": (sur, name),
             "if": (name, sur), "io": (name, patr)}[order]
    return " ".join(p for p in parts if p)


def initials(person, before: bool = False) -> str:
    sur, name, patr, _ = person
    ini = f"{name[0]}." + (f" {patr[0]}." if patr else "")
    return f"{ini} {sur}" if before else f"{sur} {ini}"


def holder(person) -> str:
    sur, name, _, _ = person
    return f"{translit(name).upper()} {translit(sur).upper()}"


def email_of(person, domain: str, style: int = 0) -> str:
    sur, name, _, _ = person
    s, n = translit(sur).replace("-", ""), translit(name)
    return (f"{n}.{s}@{domain}", f"{s}_{n[0]}@{domain}", f"{n[0]}{s}88@{domain}")[style % 3]
