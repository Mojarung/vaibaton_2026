"""Компактизация текста: склейка разорванных пробелами значений.

После OCR, распознавания речи и токенизаторов значения приходят разорванными
пробелами, вроде «5536 - 9137 - 5000 - 4321», «+7 ( 812 ) 409 56 42»,
«n . makarov @ aol . com», «Стрельцов И . И .». Правила написаны под слитную
запись, поэтому детектор прогоняется ещё раз по компактному виду текста, а
найденные спаны возвращаются на исходник через таблицу смещений.

Обычную пунктуацию трогать нельзя: «Москва. Он» и «Москва - столица» остаются
как есть. Точка склеивается, только если пробелы стоят с обеих сторон, дефис
только перед цифрой.
"""

from __future__ import annotations

import regex as re

# Быстрый префильтр: если ничего не нашёл, компактизация не нужна.
HINT = re.compile(
    r"(?:[ \t][-/.@][ \t]*[\p{L}\d]|@[ \t]|[(\[][ \t]\d|\d[ \t][)\]]|\+[ \t]\d)",
    re.VERSION1,
)

# Пробелы и табы, которые можно удалить. Сами разделители остаются.
GAPS = re.compile(
    r"(?:"
    # Пробел между буквой/цифрой и дефисом/слешем, за которым (возможно через
    # пробелы) идёт цифра: «5536 - 9137».
    r"(?<=[\p{L}\d])[ \t]+(?=[-/][ \t]*\d)"
    # Симметрично: пробел после «цифра, пробелы, дефис/слеш» перед буквой/цифрой.
    r"|(?<=[\d][ \t]*[-/])[ \t]+(?=[\p{L}\d])"
    # Пробел перед @ после буквы/цифры и после @ перед буквой/цифрой.
    r"|(?<=[\p{L}\d])[ \t]+(?=@)"
    r"|(?<=@)[ \t]+(?=[\p{L}\d])"
    # Пробел после короткого слова из 1-4 букв/цифр перед точкой, за которой
    # пробел и буква/цифра: «20 . 05», «n . makarov».
    r"|(?<=\b[\p{L}\d]{1,4})[ \t]+(?=\.[ \t]*[\p{L}\d])"
    # Пробел после буквы/цифры перед точкой, за которой пробел и короткое слово
    # из 1-4 символов с границей слова: «aol . com».
    r"|(?<=[\p{L}\d])[ \t]+(?=\.[ \t]*[\p{L}\d]{1,4}\b)"
    # Вторая половина пробельной точки: пробел после «буква/цифра, пробел,
    # точка» перед буквой/цифрой.
    r"|(?<=[\p{L}\d][ \t]*\.)[ \t]+(?=[\p{L}\d])"
    # Пробел между одиночной заглавной буквой в начале слова и точкой (инициал).
    r"|(?<=\b[\p{Lu}])[ \t]+(?=\.)"
    # Римские цифры из I, V, X длиной до четырёх с пробелами вокруг дефиса
    # перед заглавной буквой: «II - АВ».
    r"|(?<=\b[IVX]{1,4})[ \t]+(?=-[ \t]*[\p{Lu}])"
    r"|(?<=[IVX]{1,4}[ \t]*-)[ \t]+(?=[\p{Lu}])"
    # Пробелы после открывающей скобки перед цифрой и перед закрывающей скобкой
    # после цифры.
    r"|(?<=[(\[])[ \t]+(?=\d)"
    r"|(?<=\d)[ \t]+(?=[)\]])"
    # Пробел после плюса перед цифрой.
    r"|(?<=\+)[ \t]+(?=\d)"
    r")",
    re.VERSION1,
)


def compact(text: str) -> tuple[str, list[int] | None, list[int] | None]:
    """Склеивает разорванные пробелами значения.

    Возвращает кортеж из компактного текста и двух списков одинаковой длины:
    для каждого символа компактного текста начало и конец исходного символа.
    Списки равны None, если HINT не сработал или GAPS не нашёл ни одного
    совпадения.
    """
    if not HINT.search(text):
        return text, None, None
    matches = list(GAPS.finditer(text))
    if not matches:
        return text, None, None

    out: list[str] = []
    starts: list[int] = []
    ends: list[int] = []
    pos = 0
    for m in matches:
        s, e = m.span()
        if s > pos:
            out.append(text[pos:s])
            for i in range(pos, s):
                starts.append(i)
                ends.append(i + 1)
        pos = e
    if pos < len(text):
        out.append(text[pos:])
        for i in range(pos, len(text)):
            starts.append(i)
            ends.append(i + 1)
    return "".join(out), starts, ends
